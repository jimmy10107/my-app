function build(plantId, raw) {
  const idPrefix = raw.idPrefix ?? plantId;
  return raw.stages.map((stage, i) => ({
    slot: SLOTS[i],
    stageLabel: stage.stageLabel,
    file: `/models/closeup/${stage.file}.gltf`,
    bounds: stage.bounds,
    still: `/models/stills/${idPrefix}_${raw.stills[i]}.webp`,
  }));
}

export const CLOSEUP_MODELS = Object.fromEntries(
  Object.entries(RAW).map(([plantId, raw]) => [plantId, build(plantId, raw)])
);

export function closeupStagesFor(plantId) {
  return CLOSEUP_MODELS[plantId] ?? null;
}
